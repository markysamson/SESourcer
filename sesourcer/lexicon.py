_BOUNDARY = r"(?<![\w.+#]){term}(?![\w+#-])"


def skill_pattern(term: str) -> re.Pattern[str]:
    return re.compile(_BOUNDARY.format(term=re.escape(term)), re.IGNORECASE)


def find_skills(text: str) -> list[str]:
    """Return lexicon skills mentioned in text, longest match first, no overlaps."""
    if not text:
        return []
    lowered = text.lower()
    occupied = [False] * len(lowered)
    found: list[str] = []
    for skill in _SKILL_ORDER:
        needle = skill.lower()
        pattern = skill_pattern(needle)
        for match in pattern.finditer(lowered):
            start, end = match.span()
            if any(occupied[start:end]):
                continue
            for index in range(start, end):
                occupied[index] = True
            found.append(SKILL_DISPLAY[needle])
            break
    return found


def contains_term(text: str, term: str) -> bool:
    if not text or not term:
        return False
    return skill_pattern(term.strip()).search(text) is not None


def canonical_city(name: str) -> str | None:
    key = " ".join(name.lower().replace(".", "").split())
    if key in CITY_ALIASES:
        return CITY_ALIASES[key]
    if key in CITY_COUNTRY:
        return " ".join(part.capitalize() for part in key.split())
    return None


def country_of_city(city: str) -> str | None:
    key = " ".join(city.lower().replace(".", "").split())
    if key in CITY_ALIASES:
        key = CITY_ALIASES[key].lower()
    return CITY_COUNTRY.get(key)


def canonical_country(name: str) -> str | None:
    key = name.lower().strip(" .")
    canonical = COUNTRY_ALIASES.get(key)
    if not canonical:
        return None
    return COUNTRY_DISPLAY.get(canonical, canonical.title())
